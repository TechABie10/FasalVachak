# tts/sarvam_client.py
"""
Sarvam TTS wrapper for FasalVachak.

Set TTS_ENABLED=false in your .env to skip audio synthesis entirely and
just print the agent's text to the console. Useful for testing the full
LiveKit + STT + Dialogue + LLM pipeline without spending TTS credits.

When TTS_ENABLED=true (the default), text is synthesized with Sarvam's
Bulbul model and streamed through a persistent LocalAudioTrack in the room.
"""

import os

from dotenv import load_dotenv
from livekit import rtc

load_dotenv()

# ---------------------------------------------------------------------------
# Feature flags
# ---------------------------------------------------------------------------
_TTS_ENABLED = os.getenv("TTS_ENABLED", "true").strip().lower() != "false"

# Audio configuration
# SAMPLE_RATE and NUM_CHANNELS are read from the first generated audio frame
# rather than hardcoded here.

# Per-room state key so we only publish one audio track per call.
_AUDIO_SOURCE_ATTR = "_fasalvachak_audio_source"

# ---------------------------------------------------------------------------
# Lazy TTS client — only imported/instantiated when TTS is actually enabled.
# ---------------------------------------------------------------------------
_tts = None

def _get_tts():
    """Returns the Sarvam TTS client, creating it on first use."""
    global _tts
    if _tts is None:
        from livekit.plugins import sarvam
        _tts = sarvam.TTS(
            target_language_code="hi-IN",
            model=os.getenv("SARVAM_TTS_MODEL", "bulbul:v3"),
            speaker=os.getenv("SARVAM_TTS_SPEAKER", "ritu"),
            pace=float(os.getenv("SARVAM_TTS_PACE", "0.9")),
        )
    return _tts


# ---------------------------------------------------------------------------
# Audio track management (only used when TTS is enabled)
# ---------------------------------------------------------------------------

async def _ensure_audio_track(room: rtc.Room, sample_rate: int, num_channels: int) -> rtc.AudioSource:
    """
    Creates and publishes the agent's LocalAudioTrack the first time it is
    needed for this room. On subsequent calls returns the cached source.
    """
    if hasattr(room, _AUDIO_SOURCE_ATTR):
        return getattr(room, _AUDIO_SOURCE_ATTR)

    audio_source = rtc.AudioSource(
        sample_rate=sample_rate,
        num_channels=num_channels,
        queue_size_ms=1_000,
    )
    local_track = rtc.LocalAudioTrack.create_audio_track("agent-voice", audio_source)
    publish_opts = rtc.TrackPublishOptions(source=rtc.TrackSource.SOURCE_MICROPHONE)
    await room.local_participant.publish_track(local_track, publish_opts)

    setattr(room, _AUDIO_SOURCE_ATTR, audio_source)
    return audio_source


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

async def play_audio(room: rtc.Room, text: str) -> None:
    """
    Speak `text` to the farmer.

    - TTS_ENABLED=false  → prints the text to stdout only (no TTS call).
    - TTS_ENABLED=true   → synthesizes via Sarvam Bulbul and streams PCM into the room.
    """
    if not text or not text.strip():
        return

    if not _TTS_ENABLED:
        # ── Text-only mode ──────────────────────────────────────────────────
        print(f"\n[AGENT TEXT]: {text}\n")
        return

    # ── Full TTS mode ───────────────────────────────────────────────────────
    tts = _get_tts()
    audio_source = None

    try:
        async with tts.synthesize(text) as synth_stream:
            async for audio_event in synth_stream:
                frame: rtc.AudioFrame = audio_event.frame
                
                # Initialize the audio track dynamically on the exact 
                # specs of the first audio frame generated by the TTS.
                if audio_source is None:
                    audio_source = await _ensure_audio_track(room, frame.sample_rate, frame.num_channels)

                await audio_source.capture_frame(frame)
    except Exception as exc:
        print(f"[TTS] Error synthesizing '{text[:60]}...': {exc}")
        raise
